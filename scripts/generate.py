"""Generate the SDK's types and tables from the committed OpenAPI snapshot.

    uv run python scripts/generate.py          write the generated files
    uv run python scripts/generate.py --check  fail if the committed files are stale
    uv run python scripts/generate.py --snapshot live.json
                                               replace the snapshot with that document, then write

Writes src/pipsocket/_generated/{types,tables,operations}.py and one file of response examples
per operation in tests/fixtures/spec/. The document is prepared before the type generator sees
it: enums an answer can reach are made open (a newer API may send a value this SDK doesn't know),
and enums in request bodies stay closed (a typo is still a type error). An enum used on both sides
is emitted twice: open under its own name, closed with the suffix "Param".
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi.json"
GENERATED = ROOT / "src" / "pipsocket" / "_generated"
FIXTURES = ROOT / "tests" / "fixtures" / "spec"

HEADER = "# Generated by scripts/generate.py from openapi.json. Do not edit.\n"
METHODS = ("get", "post", "put", "patch", "delete")
ACCOUNT_PREFIX = "/v1/accounts/{account}"

# The document's own name for MT5's trade request clashes with the SDK's TradeRequest class
# (a recorded request). The schema is what a recorded request carries as `sent`.
RENAMES = {"TradeRequest": "SentRequest"}

Json = Any


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--snapshot", type=Path, help="a new copy of the document to adopt first")
    args = parser.parse_args()

    if args.snapshot:
        adopted = json.loads(args.snapshot.read_text(encoding="utf-8"))
        text = json.dumps(adopted, indent=2, ensure_ascii=False) + "\n"
        SNAPSHOT.write_text(text, encoding="utf-8")
    document = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    outputs = render(document)

    if args.check:
        stale = [
            str(path.relative_to(ROOT)) for path, text in outputs.items() if not same(path, text)
        ]
        expected = set(outputs)
        extra = [str(p.relative_to(ROOT)) for p in FIXTURES.glob("*.json") if p not in expected]
        if stale or extra:
            print("Generated files are stale. Run: uv run python scripts/generate.py")
            for name in stale + extra:
                print(f"  {name}")
            return 1
        print("Generated files are fresh.")
        return 0

    for old in FIXTURES.glob("*.json"):
        if old not in outputs:
            old.unlink()
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"Wrote {len(outputs)} files.")
    return 0


def same(path: Path, text: str) -> bool:
    return path.exists() and path.read_text(encoding="utf-8") == text


def render(document: Json) -> dict[Path, str]:
    outputs = {
        GENERATED / "__init__.py": HEADER,
        GENERATED / "types.py": render_types(document),
        GENERATED / "tables.py": render_tables(document),
        GENERATED / "operations.py": render_operations(document),
    }
    for operation_id, examples in response_examples(document).items():
        outputs[FIXTURES / f"{operation_id}.json"] = json.dumps(examples, indent=2) + "\n"
    return outputs


# Types


def render_types(document: Json) -> str:
    prepared = prepare(document)
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "openapi.json"
        target = Path(folder) / "types.py"
        source.write_text(json.dumps(prepared))
        subprocess.run(
            [
                "datamodel-codegen",
                "--input", str(source),
                "--input-file-type", "openapi",
                "--output", str(target),
                "--output-model-type", "typing.TypedDict",
                "--target-python-version", "3.10",
                "--enum-field-as-literal", "all",
                "--use-union-operator",
                "--use-standard-collections",
                "--no-use-closed-typed-dict",
                "--disable-timestamp",
                "--formatters", "ruff-format",
            ],
            check=True,
        )  # fmt: skip
        generated = target.read_text()
    return HEADER + "\n" + fix_imports(generated)


def fix_imports(source: str) -> str:
    """Use the standard library's TypedDict at run time: typing_extensions is not a dependency.

    NotRequired (Python 3.11) is only needed by type checkers, and the module postpones
    annotations, so it is imported for type checking only.
    """
    lines = source.splitlines()
    body = [line for line in lines if not line.startswith("# generated by datamodel-codegen")]
    body = [line for line in body if not line.startswith("#   filename:")]
    text = "\n".join(body).lstrip("\n") + "\n"
    old_typing = "from typing import Literal, TypeAlias, TypedDict\n"
    old_extensions = "from typing_extensions import NotRequired\n"
    if old_typing not in text or old_extensions not in text:
        raise SystemExit("The type generator's imports changed: update fix_imports().")
    text = text.replace(
        old_typing, "from typing import TYPE_CHECKING, Literal, TypeAlias, TypedDict\n"
    )
    return text.replace(
        old_extensions, "\nif TYPE_CHECKING:\n    from typing_extensions import NotRequired\n"
    )


def prepare(document: Json) -> Json:
    doc = copy.deepcopy(document)
    schemas: dict[str, Json] = doc["components"]["schemas"]

    for old, new in RENAMES.items():
        schemas[new] = schemas.pop(old)
    replace_refs(
        doc, {f"#/components/schemas/{o}": f"#/components/schemas/{n}" for o, n in RENAMES.items()}
    )

    answers = reachable(schemas, response_roots(doc))
    requests = reachable(schemas, request_roots(doc))

    shared = answers & requests
    shared_objects = [name for name in shared if "enum" not in schemas[name]]
    if shared_objects:
        raise SystemExit(f"Schemas used by both requests and answers: {shared_objects}")

    closed_names = {name: f"{name}Param" for name in sorted(shared)}
    for name, closed in closed_names.items():
        schemas[closed] = copy.deepcopy(schemas[name])
    refs = {
        f"#/components/schemas/{n}": f"#/components/schemas/{c}" for n, c in closed_names.items()
    }
    for name in requests - shared:
        replace_refs(schemas[name], refs)
    for path_item in doc["paths"].values():
        for method in METHODS:
            body = path_item.get(method, {}).get("requestBody")
            if body is not None:
                replace_refs(body, refs)

    for name in answers:
        schemas[name] = open_enums(schemas[name])
    return doc


def response_roots(doc: Json) -> set[str]:
    return {
        ref
        for operation in operations(doc)
        for response in operation["responses"].values()
        for ref in refs_in(response)
    }


def request_roots(doc: Json) -> set[str]:
    return {ref for operation in operations(doc) for ref in refs_in(operation.get("requestBody"))}


def reachable(schemas: dict[str, Json], roots: set[str]) -> set[str]:
    seen: set[str] = set()
    todo = list(roots)
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        todo.extend(refs_in(schemas[name]))
    return seen


def refs_in(node: Json) -> Iterator[str]:
    if isinstance(node, dict):
        for key, value in cast(dict[str, Json], node).items():
            if (
                key == "$ref"
                and isinstance(value, str)
                and value.startswith("#/components/schemas/")
            ):
                yield value.removeprefix("#/components/schemas/")
            else:
                yield from refs_in(value)
    elif isinstance(node, list):
        for item in cast(list[Json], node):
            yield from refs_in(item)


def replace_refs(node: Json, mapping: dict[str, str]) -> None:
    if isinstance(node, dict):
        node = cast(dict[str, Json], node)
        ref = node.get("$ref")
        if isinstance(ref, str) and ref in mapping:
            node["$ref"] = mapping[ref]
        for value in node.values():
            replace_refs(value, mapping)
    elif isinstance(node, list):
        for item in cast(list[Json], node):
            replace_refs(item, mapping)


def open_enums(node: Json) -> Json:
    """Every string enum in the schema also accepts any other string (null stays allowed)."""
    if isinstance(node, list):
        return [open_enums(item) for item in cast(list[Json], node)]
    if not isinstance(node, dict):
        return node
    node = {key: open_enums(value) for key, value in cast(dict[str, Json], node).items()}
    values = node.get("enum")
    if not isinstance(values, list):
        return node
    values = cast(list[Json], values)
    known = [value for value in values if value is not None]
    if not all(isinstance(value, str) for value in known):
        return node
    nullable = None in values or (isinstance(node.get("type"), list) and "null" in node["type"])
    keep = {key: value for key, value in node.items() if key not in ("type", "enum")}
    branches: list[Json] = [{"type": "string", "enum": known}, {"type": "string"}]
    if nullable:
        branches.append({"type": "null"})
    return {**keep, "anyOf": branches}


def operations(doc: Json) -> Iterator[Json]:
    for path_item in doc["paths"].values():
        for method in METHODS:
            if method in path_item:
                yield path_item[method]


# Tables


def render_tables(document: Json) -> str:
    extension = document["x-pipsocket"]
    errors = {entry["code"]: entry["status"] for entry in extension["errors"]}
    retcodes = {entry["code"]: (entry["name"], entry["message"]) for entry in extension["retcodes"]}
    states = document["components"]["schemas"]["RequestState"]["enum"]
    lines = [
        HEADER,
        '"""Tables from the document\'s `x-pipsocket` extension and its request states."""',
        "",
        "from typing import Final",
        "",
        "# Every error code the API answers with, and its HTTP status.",
        "ERROR_STATUS: Final[dict[str, int]] = {",
        *[f"    {json.dumps(code)}: {status}," for code, status in errors.items()],
        "}",
        "",
        "# MT5's retcodes: the name the API sends in `retcode_name`, and what it means.",
        "RETCODES: Final[dict[int, tuple[str, str]]] = {",
        *[f"    {code}: ({json.dumps(n)}, {json.dumps(m)})," for code, (n, m) in retcodes.items()],
        "}",
        "",
        "# The states a recorded request can be in.",
        "REQUEST_STATES: Final[tuple[str, ...]] = (",
        *[f"    {json.dumps(state)}," for state in states],
        ")",
        "",
    ]
    return "\n".join(lines)


def render_operations(document: Json) -> str:
    lines = [
        HEADER,
        '"""Every operation in the document: its id, method, path under the account and key."""',
        "",
        "from typing import Final, NamedTuple",
        "",
        "",
        "class Operation(NamedTuple):",
        "    id: str",
        "    method: str",
        "    path: str",
        "    keyed: bool",
        "",
        "",
        "OPERATIONS: Final[tuple[Operation, ...]] = (",
    ]
    for path, path_item in document["paths"].items():
        if not path.startswith(ACCOUNT_PREFIX):
            raise SystemExit(f"An operation outside {ACCOUNT_PREFIX}: {path}")
        relative = path.removeprefix(ACCOUNT_PREFIX) or "/"
        for method in METHODS:
            if method not in path_item:
                continue
            operation = path_item[method]
            keyed = any(p.get("name") == "Idempotency-Key" for p in operation.get("parameters", []))
            fields = [json.dumps(operation["operationId"]), json.dumps(method.upper())]
            fields += [json.dumps(relative), str(keyed)]
            lines.append(f"    Operation({', '.join(fields)}),")
    lines += [")", ""]
    return "\n".join(lines)


# Fixtures


def response_examples(document: Json) -> dict[str, dict[str, dict[str, Json]]]:
    """Each operation's named response examples, by status and name."""
    found: dict[str, dict[str, dict[str, Json]]] = {}
    for operation in operations(document):
        by_status: dict[str, dict[str, Json]] = {}
        for status, response in operation["responses"].items():
            examples = response.get("content", {}).get("application/json", {}).get("examples", {})
            if examples:
                by_status[status] = {name: e["value"] for name, e in examples.items()}
        found[operation["operationId"]] = by_status
    return found


if __name__ == "__main__":
    sys.exit(main())
